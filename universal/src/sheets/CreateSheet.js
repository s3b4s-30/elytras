import React, { useState, useMemo, useEffect } from 'react';
import { View, Text, ScrollView } from 'react-native';
import { Ionicons } from '@expo/vector-icons';
import { useTheme } from '../ThemeContext';
import { Sheet, Field, PriceInput, PrimaryButton, Chip, BackButton, Dot, Tap, Txt, haptic } from '../ui/kit';
import { SuppliersSheet } from './TopMenu';
import {
  CHARGER_SUBTYPES,
  CUBO_BRANDS,
  CABLE_BRANDS,
  PREMIUM_BRANDS,
  CHARGER_WATTS_LIST,
  CABLE_CONNECTORS,
  CABLE_FINISHES,
  CASE_MATERIALS,
  IPHONE_SHARED_MODELS,
  AUDIO_MODELS,
  AUDIO_CONNECTIONS,
  INITIAL_NEW_PRODUCT_FORM,
  buildAutoGeneratedProductMeta,
} from '../domain/productTaxonomy';

const Group = ({ label, children }) => {
  const t = useTheme();
  return (
    <View style={{ marginBottom: 10 }}>
      <Text style={{ color: t.text2, fontSize: 12, marginLeft: 4, marginBottom: 6 }}>{label}</Text>
      <ScrollView horizontal showsHorizontalScrollIndicator={false}>
        {children}
      </ScrollView>
    </View>
  );
};

const Opts = ({ label, items, value, onChange, multi }) => (
  <Group label={label}>
    {items.map((it) => {
      const id = it.id || it;
      const active = multi ? value.includes(id) : value === id;
      return (
        <Chip
          key={id}
          label={it.label || it}
          active={active}
          onPress={() =>
            multi ? onChange(active ? value.filter((v) => v !== id) : [...value, id]) : onChange(id)
          }
        />
      );
    })}
  </Group>
);

const TYPES = [
  { id: 'cargadores', label: 'Cargadores y Cables' },
  { id: 'forros', label: 'Forros / Fundas' },
  { id: 'audio', label: 'Audio / AirPods' },
];

function SupplierPickerField({ suppliers, value, onChange, onManage }) {
  const t = useTheme();
  const [open, setOpen] = useState(false);
  const selected = suppliers.find((s) => s.id === value);

  return (
    <View style={{ marginBottom: 14 }}>
      <View style={{ flexDirection: 'row', alignItems: 'center', justifyContent: 'space-between', marginBottom: 6, marginLeft: 4 }}>
        <Text style={{ color: t.text2, fontSize: 12 }}>Proveedor (Obligatorio)</Text>
        <Tap onPress={onManage} hapticKind="select">
          <Text style={{ color: t.blue, fontSize: 12, fontWeight: '600' }}>+ Gestionar proveedores</Text>
        </Tap>
      </View>
      <Tap onPress={() => setOpen((v) => !v)} hapticKind="select">
        <View
          style={{
            flexDirection: 'row',
            alignItems: 'center',
            backgroundColor: t.card2,
            borderRadius: 14,
            paddingHorizontal: 14,
            minHeight: 48,
            borderWidth: 1,
            borderColor: selected ? t.border : 'rgba(255,149,0,0.6)',
          }}
        >
          {selected ? (
            <Dot color={selected.color} size={12} />
          ) : (
            <Ionicons name="alert-circle-outline" size={16} color={t.orange} />
          )}
          <Text
            style={{
              flex: 1,
              color: selected ? t.text : t.text3,
              fontSize: 15,
              marginLeft: 10,
              fontWeight: '600',
            }}
          >
            {selected ? selected.name : 'Selecciona un proveedor existente...'}
          </Text>
          <Ionicons name={open ? 'chevron-up' : 'chevron-down'} size={18} color={t.text2} />
        </View>
      </Tap>

      {/* Lista desplegable con selección rápida */}
      {open && (
        <View
          style={{
            backgroundColor: t.card,
            borderRadius: 16,
            borderWidth: 1,
            borderColor: t.border,
            marginTop: 8,
            overflow: 'hidden',
          }}
        >
          {suppliers.map((s) => {
            const isSel = s.id === value;
            return (
              <Tap
                key={s.id}
                onPress={() => {
                  onChange(s.id);
                  setOpen(false);
                }}
                hapticKind="select"
              >
                <View
                  style={{
                    flexDirection: 'row',
                    alignItems: 'center',
                    paddingVertical: 12,
                    paddingHorizontal: 14,
                    borderBottomWidth: 0.5,
                    borderBottomColor: t.hairline,
                    backgroundColor: isSel ? t.card2 : 'transparent',
                  }}
                >
                  <Dot color={s.color} size={12} />
                  <View style={{ flex: 1, marginLeft: 10 }}>
                    <Text style={{ color: t.text, fontWeight: '600', fontSize: 14 }}>{s.name}</Text>
                    {s.contact ? <Txt style={{ color: t.text2, fontSize: 12 }}>{s.contact}</Txt> : null}
                  </View>
                  {isSel && <Ionicons name="checkmark" size={18} color={t.blue} />}
                </View>
              </Tap>
            );
          })}
        </View>
      )}
    </View>
  );
}

export function CreateSheet({ visible, onClose, store }) {
  const t = useTheme();
  const blank = {
    ...INITIAL_NEW_PRODUCT_FORM,
    selectedModels: ['iPhone 13 / 14'],
    stock: '',
    defaultWarrantyDays: 15,
  };
  const [f, setF] = useState(blank);
  const [name, setName] = useState('');
  const [showManageSuppliers, setShowManageSuppliers] = useState(false);
  const set = (k) => (v) => setF((p) => ({ ...p, [k]: v }));

  const meta = useMemo(() => buildAutoGeneratedProductMeta({ ...f, basedOnProductId: '' }), [f]);
  useEffect(() => setName(meta.name), [meta.name]);
  useEffect(() => {
    if (visible) {
      setF({ ...blank, supplierId: store.lastSupplierId || store.suppliers[0]?.id || '' });
    }
  }, [visible, store.lastSupplierId, store.suppliers]);

  const canSave =
    f.salePrice !== '' &&
    f.unitCost !== '' &&
    Number(f.stock) > 0 &&
    name.trim() &&
    Boolean(f.supplierId);

  const save = () => {
    const sup = store.suppliers.find((s) => s.id === f.supplierId);
    const qty = Number(f.stock);
    store.createProduct({
      id: `prod-${Date.now()}`,
      name: name.trim(),
      category: meta.category,
      specs: meta.specs,
      salePrice: Number(f.salePrice),
      unitCost: Number(f.unitCost),
      stock: qty,
      defaultWarrantyDays: Number(f.defaultWarrantyDays) || 15,
      supplierId: f.supplierId,
      lastAddedAt: new Date().toISOString(),
      batches: [
        {
          id: `lot-${Date.now()}`,
          date: new Date().toISOString().slice(0, 10),
          qty,
          unitCost: Number(f.unitCost),
          supplierId: f.supplierId,
          supplierName: sup?.name || '',
        },
      ],
    });
    haptic('success');
    onClose();
  };

  const showCubo = f.chargerSubtype === 'cubito';
  const isCable = f.chargerSubtype === 'cable';
  const isComplete = f.chargerSubtype === 'completo';

  return (
    <>
      <Sheet visible={visible} onClose={onClose} title="Nuevo producto" height={0.94}>
        <ScrollView contentContainerStyle={{ padding: 16, paddingBottom: 40 }} keyboardShouldPersistTaps="handled">
          <Opts label="Categoría" items={TYPES} value={f.type} onChange={set('type')} />

          {f.type === 'cargadores' && (
            <>
              <Opts label="Subtipo" items={CHARGER_SUBTYPES} value={f.chargerSubtype} onChange={set('chargerSubtype')} />
              {(showCubo || isComplete) && <Opts label="Marca" items={CUBO_BRANDS} value={f.cuboBrand} onChange={set('cuboBrand')} />}
              {isCable && <Opts label="Marca" items={CABLE_BRANDS} value={f.cuboBrand} onChange={set('cuboBrand')} />}
              <Opts label="Potencia" items={CHARGER_WATTS_LIST} value={f.watts} onChange={set('watts')} />
              {(isCable || isComplete) && (
                <Opts label="Conector" items={CABLE_CONNECTORS} value={f.cableConnector} onChange={set('cableConnector')} />
              )}
              {!showCubo && <Opts label="Acabado" items={CABLE_FINISHES} value={f.cableFinish} onChange={set('cableFinish')} />}
            </>
          )}
          {f.type === 'forros' && (
            <>
              <Opts label="Material" items={CASE_MATERIALS} value={f.material} onChange={set('material')} />
              <Opts label="Modelos" items={IPHONE_SHARED_MODELS} value={f.selectedModels} onChange={set('selectedModels')} multi />
            </>
          )}
          {f.type === 'audio' && (
            <>
              <Opts label="Modelo" items={AUDIO_MODELS} value={f.audioModel} onChange={set('audioModel')} />
              <Opts label="Conexión" items={AUDIO_CONNECTIONS} value={f.audioConnection} onChange={set('audioConnection')} />
            </>
          )}

          <Field label="Nombre" value={name} onChangeText={setName} />
          <PriceInput label="Precio de venta" value={f.salePrice} onChange={set('salePrice')} />
          <PriceInput label="Costo de compra" value={f.unitCost} onChange={set('unitCost')} />
          <Field label="Cantidad" keyboardType="number-pad" value={String(f.stock)} onChangeText={set('stock')} placeholder="0" />
          <Field
            label="Garantía (días)"
            keyboardType="number-pad"
            value={String(f.defaultWarrantyDays)}
            onChangeText={set('defaultWarrantyDays')}
          />

          {/* Selector desplegable de proveedor obligatorio + gestión directa */}
          <SupplierPickerField
            suppliers={store.suppliers}
            value={f.supplierId}
            onChange={set('supplierId')}
            onManage={() => setShowManageSuppliers(true)}
          />

          <PrimaryButton title="Guardar producto" onPress={save} disabled={!canSave} />
        </ScrollView>
      </Sheet>

      {/* Modal para administrar o crear nuevos proveedores al momento */}
      <SuppliersSheet
        visible={showManageSuppliers}
        onClose={() => setShowManageSuppliers(false)}
        store={store}
      />
    </>
  );
}
