import React, { useState, useMemo, useEffect } from 'react';
import { COLORS } from '../../theme/designSystem.js';
import { formatPriceInput, parsePriceInput } from '../../utils/formatters.js';
import IOSBottomSheet from '../../components/IOSBottomSheet.jsx';
import IOSSupplierPicker from '../../components/IOSSupplierPicker.jsx';
import {
  IPHONE_SHARED_MODELS,
  CASE_MATERIALS,
  CHARGER_SUBTYPES,
  CUBO_BRANDS,
  CABLE_BRANDS,
  PREMIUM_BRANDS,
  CHARGER_WATTS_LIST,
  CABLE_CONNECTORS,
  CABLE_FINISHES,
  ANKER_BELKIN_MODALITIES,
  AUDIO_MODELS,
  AUDIO_CONNECTIONS,
  INITIAL_NEW_PRODUCT_FORM,
  buildAutoGeneratedProductMeta,
} from '../../constants/productTaxonomy.js';

/**
 * src/views/inventario/CreateAccessorySheet.jsx
 * Modal "Registrar Nuevo Accesorio" desacoplado bajo el principio de responsabilidad única (SRP):
 * - Buscador "¿Basado en un producto existente?" con lupa al lado del título y flecha desplegable a la derecha.
 * - 3 categorías dinámicas ("Cargadores y Cables", "Forros / Fundas", "Audio / AirPods") con Watts hasta 60W.
 * - Tarjeta "FICHA TÉCNICA" limpia y precios 100% decididos al momento.
 */
export default function CreateAccessorySheet({
  open,
  onClose,
  products = [],
  suppliers = [],
  lastSupplierId,
  onCreateProduct,
}) {
  const [existingSearchQuery, setExistingSearchQuery] = useState('');
  const [existingPickerOpen, setExistingPickerOpen] = useState(false);

  const [newProdForm, setNewProdForm] = useState(() => ({
    ...INITIAL_NEW_PRODUCT_FORM,
    supplierId: lastSupplierId || suppliers[0]?.id || '',
  }));

  useEffect(() => {
    if (open) {
      setExistingSearchQuery('');
      setExistingPickerOpen(false);
      setNewProdForm((prev) => ({
        ...prev,
        basedOnProductId: '',
        customName: '',
        customCategory: '',
        customSpecsText: '',
        salePrice: '',
        unitCost: '',
        supplierId: lastSupplierId || suppliers[0]?.id || '',
      }));
    }
  }, [open, lastSupplierId, suppliers]);

  const matchingExistingProducts = useMemo(() => {
    const q = existingSearchQuery.trim().toLowerCase();
    if (!q) return products.slice(0, 10);
    return products
      .filter(
        (p) =>
          p.name.toLowerCase().includes(q) ||
          p.category.toLowerCase().includes(q) ||
          p.specs.some((s) => s.toLowerCase().includes(q))
      )
      .slice(0, 10);
  }, [products, existingSearchQuery]);

  const autoGeneratedProductMeta = useMemo(
    () => buildAutoGeneratedProductMeta(newProdForm),
    [newProdForm]
  );

  const handleSelectExistingTemplate = (prod) => {
    setNewProdForm((prev) => ({
      ...prev,
      basedOnProductId: prod.id,
      customName: prod.name,
      customCategory: ['Carga Rápida', 'Cables', 'Carga y Cables'].includes(
        prod.category
      )
        ? 'Cargadores y Cables'
        : prod.category,
      customSpecsText: (prod.specs || []).join(', '),
      defaultWarrantyDays: prod.defaultWarrantyDays || 90,
      salePrice: '',
      unitCost: '',
      supplierId: lastSupplierId || prod.supplierId || suppliers[0]?.id || '',
    }));
    setExistingSearchQuery(prod.name);
    setExistingPickerOpen(false);
  };

  const handleClearExistingTemplate = () => {
    setExistingSearchQuery('');
    setExistingPickerOpen(false);
    setNewProdForm((prev) => ({
      ...prev,
      basedOnProductId: '',
      customName: '',
      customCategory: '',
      customSpecsText: '',
    }));
  };

  const handleToggleModelSelection = (modelName) => {
    setNewProdForm((prev) => {
      const exists = prev.selectedModels.includes(modelName);
      if (exists) {
        if (prev.selectedModels.length <= 1) return prev;
        return {
          ...prev,
          selectedModels: prev.selectedModels.filter((m) => m !== modelName),
        };
      }
      return {
        ...prev,
        selectedModels: [...prev.selectedModels, modelName],
      };
    });
  };

  const handleSubmit = (e) => {
    e.preventDefault();
    const finalName = autoGeneratedProductMeta.name;
    if (!finalName) return;

    const supplier =
      suppliers.find((s) => s.id === newProdForm.supplierId) || suppliers[0];

    onCreateProduct({
      id: `prod-${Date.now()}`,
      name: finalName,
      category: autoGeneratedProductMeta.category,
      specs: autoGeneratedProductMeta.specs,
      salePrice: Number(newProdForm.salePrice) || 0,
      unitCost: Number(newProdForm.unitCost) || 0,
      stock: Number(newProdForm.stock) || 0,
      defaultWarrantyDays: Number(newProdForm.defaultWarrantyDays) || 30,
      supplierId: supplier?.id || 'sup-1',
      lastAddedAt: new Date().toISOString(),
      lastSoldAt: null,
      batches: [
        {
          id: `lot-${Date.now()}`,
          date: new Date().toISOString().slice(0, 10),
          qty: Number(newProdForm.stock) || 0,
          unitCost: Number(newProdForm.unitCost) || 0,
          supplierId: supplier?.id || 'sup-1',
          supplierName: supplier?.name || 'Mayorista Principal',
        },
      ],
    });

    onClose();
  };

  return (
    <IOSBottomSheet open={open} onClose={onClose} maxWidthClass="max-w-lg">
      <form onSubmit={handleSubmit} className="space-y-3.5">
        <div className="flex items-center justify-between gap-2">
          <div className="flex items-center gap-2.5 min-w-0">
            <button
              type="button"
              onClick={onClose}
              aria-label="Regresar"
              title="Regresar"
              className="w-11 h-11 rounded-full flex items-center justify-center transition-transform active:scale-[0.97] cursor-pointer hig-border shrink-0"
              style={{
                backgroundColor: 'var(--bg-secondary)',
                color: COLORS.electricBlue,
              }}
            >
              <svg
                width="18"
                height="18"
                viewBox="0 0 24 24"
                fill="none"
                stroke="currentColor"
                strokeWidth="2.5"
                strokeLinecap="round"
                strokeLinejoin="round"
              >
                <polyline points="15 18 9 12 15 6" />
              </svg>
            </button>
            <h3 className="text-base font-bold truncate">Registrar Nuevo Accesorio</h3>
          </div>
          <button
            type="button"
            onClick={onClose}
            className="px-3 py-1.5 rounded-full text-xs font-semibold cursor-pointer shrink-0"
            style={{
              backgroundColor: 'var(--bg-secondary)',
              color: COLORS.electricBlue,
            }}
          >
            Cerrar
          </button>
        </div>

        {/* A. Selector "¿Basado en un producto existente?": Lupa al lado del título y flecha desplegable a la derecha */}
        <div
          className="p-3 rounded-2xl space-y-2 hig-border"
          style={{ backgroundColor: 'var(--bg-secondary)' }}
        >
          <div className="flex items-center justify-between gap-2">
            <label
              className="text-[11px] font-bold flex items-center gap-1.5"
              style={{ color: COLORS.electricBlue }}
            >
              <svg
                width="13"
                height="13"
                viewBox="0 0 24 24"
                fill="none"
                stroke="currentColor"
                strokeWidth="2.5"
              >
                <circle cx="11" cy="11" r="8" />
                <line x1="21" y1="21" x2="16.65" y2="16.65" />
              </svg>
              <span>¿Basado en un producto existente?</span>
            </label>

            {newProdForm.basedOnProductId && (
              <button
                type="button"
                onClick={handleClearExistingTemplate}
                className="text-[10px] font-bold px-2 py-0.5 rounded-full cursor-pointer"
                style={{
                  backgroundColor: COLORS.dangerRedSoft,
                  color: COLORS.dangerRed,
                }}
              >
                ✕ Limpiar
              </button>
            )}
          </div>

          <div className="relative">
            <input
              type="search"
              placeholder="Buscar en catálogo actual..."
              value={existingSearchQuery}
              onFocus={() => setExistingPickerOpen(true)}
              onChange={(e) => {
                setExistingSearchQuery(e.target.value);
                setExistingPickerOpen(true);
              }}
              className="hig-input w-full py-2 text-xs"
              style={{
                backgroundColor: 'var(--bg-elevated-solid)',
                paddingLeft: '14px',
                paddingRight: '38px',
              }}
            />
            <button
              type="button"
              aria-label="Desplegar productos existentes"
              onClick={() => setExistingPickerOpen((prev) => !prev)}
              className="w-6 h-6 rounded-full flex items-center justify-center cursor-pointer"
              style={{
                position: 'absolute',
                right: '8px',
                top: '50%',
                transform: 'translateY(-50%)',
                color: COLORS.electricBlue,
              }}
            >
              <svg
                width="14"
                height="14"
                viewBox="0 0 24 24"
                fill="none"
                stroke="currentColor"
                strokeWidth="2.5"
                style={{
                  transform: existingPickerOpen ? 'rotate(180deg)' : 'rotate(0deg)',
                  transition: 'transform 0.2s cubic-bezier(0.22, 1, 0.36, 1)',
                }}
              >
                <polyline points="6 9 12 15 18 9" />
              </svg>
            </button>
          </div>

          {existingPickerOpen && matchingExistingProducts.length > 0 && (
            <div
              className="max-h-44 overflow-y-auto ios-scroll-inertia rounded-2xl p-1.5 space-y-1 hig-border animate-ios-expand"
              style={{ backgroundColor: 'var(--bg-elevated-solid)' }}
            >
              {matchingExistingProducts.map((prod) => {
                const isChosen = newProdForm.basedOnProductId === prod.id;
                return (
                  <button
                    key={prod.id}
                    type="button"
                    onClick={() => handleSelectExistingTemplate(prod)}
                    className="tactile-chip w-full p-2.5 rounded-xl text-left flex items-center justify-between gap-2 cursor-pointer hig-border"
                    style={{
                      backgroundColor: isChosen
                        ? COLORS.electricBlueSoft
                        : 'var(--bg-secondary)',
                      borderColor: isChosen ? COLORS.electricBlue : 'var(--border-card)',
                    }}
                  >
                    <div className="min-w-0">
                      <div className="text-xs font-bold truncate">{prod.name}</div>
                      <div
                        className="text-[10px] truncate mt-0.5"
                        style={{ color: 'var(--text-secondary)' }}
                      >
                        {prod.category} • {(prod.specs || []).join(' · ')}
                      </div>
                    </div>
                    {isChosen && (
                      <span
                        className="text-[10px] font-bold px-2 py-0.5 rounded-full shrink-0"
                        style={{
                          backgroundColor: COLORS.electricBlue,
                          color: '#FFFFFF',
                        }}
                      >
                        ✓
                      </span>
                    )}
                  </button>
                );
              })}
            </div>
          )}
        </div>

        {/* B. Selector de las 3 Categorías Dinámicas */}
        {!newProdForm.basedOnProductId && (
          <>
            <div
              className="grid grid-cols-3 gap-1.5 p-1 rounded-2xl hig-border"
              style={{ backgroundColor: 'var(--bg-secondary)' }}
            >
              {[
                { id: 'cargadores', label: 'Cargadores y Cables' },
                { id: 'forros', label: 'Forros / Fundas' },
                { id: 'audio', label: 'Audio / AirPods' },
              ].map((tab) => {
                const active = newProdForm.type === tab.id;
                return (
                  <button
                    key={tab.id}
                    type="button"
                    onClick={() =>
                      setNewProdForm((prev) => ({ ...prev, type: tab.id }))
                    }
                    className="tactile-chip py-2 px-2 rounded-xl text-[11px] font-bold cursor-pointer text-center leading-tight"
                    style={{
                      backgroundColor: active ? COLORS.electricBlue : 'transparent',
                      color: active ? '#FFFFFF' : 'var(--text-secondary)',
                    }}
                  >
                    {tab.label}
                  </button>
                );
              })}
            </div>

            {/* 1. Categoría: Cargadores y Cables */}
            {newProdForm.type === 'cargadores' && (
              <div
                className="p-3.5 rounded-2xl space-y-3 hig-border animate-ios-expand"
                style={{ backgroundColor: 'var(--bg-secondary)' }}
              >
                <div>
                  <label
                    className="block text-[11px] font-bold mb-1.5"
                    style={{ color: 'var(--text-secondary)' }}
                  >
                    Subtipo de Carga / Línea
                  </label>
                  <div className="grid grid-cols-2 gap-1.5">
                    {CHARGER_SUBTYPES.map((sub) => {
                      const active = newProdForm.chargerSubtype === sub.id;
                      return (
                        <button
                          key={sub.id}
                          type="button"
                          onClick={() =>
                            setNewProdForm((prev) => ({
                              ...prev,
                              chargerSubtype: sub.id,
                            }))
                          }
                          className="tactile-chip py-2 px-2.5 rounded-xl text-xs font-semibold cursor-pointer hig-border text-center"
                          style={{
                            backgroundColor: active
                              ? COLORS.electricBlue
                              : 'var(--bg-elevated-solid)',
                            color: active ? '#FFFFFF' : 'var(--text-primary)',
                            borderColor: active ? 'transparent' : 'var(--border-card)',
                          }}
                        >
                          {sub.label}
                        </button>
                      );
                    })}
                  </div>
                </div>

                {/* CUBITO CARGADOR */}
                {newProdForm.chargerSubtype === 'cubito' && (
                  <div className="space-y-3 animate-ios-expand">
                    <div>
                      <label
                        className="block text-[11px] font-bold mb-1.5"
                        style={{ color: 'var(--text-secondary)' }}
                      >
                        Marca / Tipo de Cubito
                      </label>
                      <div className="flex flex-wrap gap-1.5">
                        {CUBO_BRANDS.map((brand) => {
                          const active = newProdForm.cuboBrand === brand;
                          return (
                            <button
                              key={brand}
                              type="button"
                              onClick={() =>
                                setNewProdForm((prev) => ({
                                  ...prev,
                                  cuboBrand: brand,
                                }))
                              }
                              className="tactile-chip px-3 py-1.5 rounded-xl text-xs font-bold cursor-pointer hig-border"
                              style={{
                                backgroundColor: active
                                  ? COLORS.electricBlue
                                  : 'var(--bg-elevated-solid)',
                                color: active ? '#FFFFFF' : 'var(--text-primary)',
                                borderColor: active
                                  ? 'transparent'
                                  : 'var(--border-card)',
                              }}
                            >
                              {brand}
                            </button>
                          );
                        })}
                      </div>
                    </div>

                    <div>
                      <label
                        className="block text-[11px] font-bold mb-1.5"
                        style={{ color: 'var(--text-secondary)' }}
                      >
                        Potencia (Watts)
                      </label>
                      <div className="grid grid-cols-3 sm:grid-cols-6 gap-1.5">
                        {CHARGER_WATTS_LIST.map((w) => {
                          const active = newProdForm.watts === w;
                          return (
                            <button
                              key={w}
                              type="button"
                              onClick={() =>
                                setNewProdForm((prev) => ({ ...prev, watts: w }))
                              }
                              className="tactile-chip cop-mono py-1.5 px-2 rounded-xl text-xs font-extrabold cursor-pointer hig-border text-center"
                              style={{
                                backgroundColor: active
                                  ? COLORS.electricBlue
                                  : 'var(--bg-elevated-solid)',
                                color: active ? '#FFFFFF' : 'var(--text-primary)',
                                borderColor: active
                                  ? 'transparent'
                                  : 'var(--border-card)',
                              }}
                            >
                              {w}
                            </button>
                          );
                        })}
                      </div>
                    </div>
                  </div>
                )}

                {/* CABLE */}
                {newProdForm.chargerSubtype === 'cable' && (
                  <div className="space-y-3 animate-ios-expand">
                    <div>
                      <label
                        className="block text-[11px] font-bold mb-1.5"
                        style={{ color: 'var(--text-secondary)' }}
                      >
                        Conector del Cable
                      </label>
                      <div className="grid grid-cols-1 sm:grid-cols-3 gap-1.5">
                        {CABLE_CONNECTORS.map((conn) => {
                          const active = newProdForm.cableConnector === conn;
                          return (
                            <button
                              key={conn}
                              type="button"
                              onClick={() =>
                                setNewProdForm((prev) => ({
                                  ...prev,
                                  cableConnector: conn,
                                }))
                              }
                              className="tactile-chip py-2 px-2.5 rounded-xl text-xs font-semibold cursor-pointer hig-border text-center"
                              style={{
                                backgroundColor: active
                                  ? COLORS.electricBlue
                                  : 'var(--bg-elevated-solid)',
                                color: active ? '#FFFFFF' : 'var(--text-primary)',
                                borderColor: active
                                  ? 'transparent'
                                  : 'var(--border-card)',
                              }}
                            >
                              {conn}
                            </button>
                          );
                        })}
                      </div>
                    </div>

                    <div>
                      <label
                        className="block text-[11px] font-bold mb-1.5"
                        style={{ color: 'var(--text-secondary)' }}
                      >
                        Material / Acabado
                      </label>
                      <div className="grid grid-cols-2 gap-1.5">
                        {CABLE_FINISHES.map((fin) => {
                          const active = newProdForm.cableFinish === fin;
                          return (
                            <button
                              key={fin}
                              type="button"
                              onClick={() =>
                                setNewProdForm((prev) => ({
                                  ...prev,
                                  cableFinish: fin,
                                }))
                              }
                              className="tactile-chip py-2 px-3 rounded-xl text-xs font-bold cursor-pointer hig-border text-center"
                              style={{
                                backgroundColor: active
                                  ? COLORS.electricBlue
                                  : 'var(--bg-elevated-solid)',
                                color: active ? '#FFFFFF' : 'var(--text-primary)',
                                borderColor: active
                                  ? 'transparent'
                                  : 'var(--border-card)',
                              }}
                            >
                              {fin}
                            </button>
                          );
                        })}
                      </div>
                    </div>

                    <div>
                      <label
                        className="block text-[11px] font-bold mb-1.5"
                        style={{ color: 'var(--text-secondary)' }}
                      >
                        Marca / Línea
                      </label>
                      <div className="flex flex-wrap gap-1.5">
                        {CABLE_BRANDS.map((brand) => {
                          const active = newProdForm.cuboBrand === brand;
                          return (
                            <button
                              key={brand}
                              type="button"
                              onClick={() =>
                                setNewProdForm((prev) => ({
                                  ...prev,
                                  cuboBrand: brand,
                                }))
                              }
                              className="tactile-chip px-3 py-1.5 rounded-xl text-xs font-bold cursor-pointer hig-border"
                              style={{
                                backgroundColor: active
                                  ? COLORS.electricBlue
                                  : 'var(--bg-elevated-solid)',
                                color: active ? '#FFFFFF' : 'var(--text-primary)',
                                borderColor: active
                                  ? 'transparent'
                                  : 'var(--border-card)',
                              }}
                            >
                              {brand}
                            </button>
                          );
                        })}
                      </div>
                    </div>

                    <div>
                      <label
                        className="block text-[11px] font-bold mb-1.5"
                        style={{ color: 'var(--text-secondary)' }}
                      >
                        Potencia Soportada (Watts)
                      </label>
                      <div className="grid grid-cols-3 sm:grid-cols-6 gap-1.5">
                        {CHARGER_WATTS_LIST.map((w) => {
                          const active = newProdForm.watts === w;
                          return (
                            <button
                              key={w}
                              type="button"
                              onClick={() =>
                                setNewProdForm((prev) => ({ ...prev, watts: w }))
                              }
                              className="tactile-chip cop-mono py-1.5 px-2 rounded-xl text-xs font-extrabold cursor-pointer hig-border text-center"
                              style={{
                                backgroundColor: active
                                  ? COLORS.electricBlue
                                  : 'var(--bg-elevated-solid)',
                                color: active ? '#FFFFFF' : 'var(--text-primary)',
                                borderColor: active
                                  ? 'transparent'
                                  : 'var(--border-card)',
                              }}
                            >
                              {w}
                            </button>
                          );
                        })}
                      </div>
                    </div>
                  </div>
                )}

                {/* COMPLETO [CUBO + CABLE] */}
                {newProdForm.chargerSubtype === 'completo' && (
                  <div className="space-y-3 animate-ios-expand">
                    <div>
                      <label
                        className="block text-[11px] font-bold mb-1.5"
                        style={{ color: 'var(--text-secondary)' }}
                      >
                        Marca / Tipo de Cargador
                      </label>
                      <div className="flex flex-wrap gap-1.5">
                        {CUBO_BRANDS.map((brand) => {
                          const active = newProdForm.cuboBrand === brand;
                          return (
                            <button
                              key={brand}
                              type="button"
                              onClick={() =>
                                setNewProdForm((prev) => ({
                                  ...prev,
                                  cuboBrand: brand,
                                }))
                              }
                              className="tactile-chip px-3 py-1.5 rounded-xl text-xs font-bold cursor-pointer hig-border"
                              style={{
                                backgroundColor: active
                                  ? COLORS.electricBlue
                                  : 'var(--bg-elevated-solid)',
                                color: active ? '#FFFFFF' : 'var(--text-primary)',
                                borderColor: active
                                  ? 'transparent'
                                  : 'var(--border-card)',
                              }}
                            >
                              {brand}
                            </button>
                          );
                        })}
                      </div>
                    </div>

                    <div>
                      <label
                        className="block text-[11px] font-bold mb-1.5"
                        style={{ color: 'var(--text-secondary)' }}
                      >
                        Potencia del Cubo (Watts)
                      </label>
                      <div className="grid grid-cols-3 sm:grid-cols-6 gap-1.5">
                        {CHARGER_WATTS_LIST.map((w) => {
                          const active = newProdForm.watts === w;
                          return (
                            <button
                              key={w}
                              type="button"
                              onClick={() =>
                                setNewProdForm((prev) => ({ ...prev, watts: w }))
                              }
                              className="tactile-chip cop-mono py-1.5 px-2 rounded-xl text-xs font-extrabold cursor-pointer hig-border text-center"
                              style={{
                                backgroundColor: active
                                  ? COLORS.electricBlue
                                  : 'var(--bg-elevated-solid)',
                                color: active ? '#FFFFFF' : 'var(--text-primary)',
                                borderColor: active
                                  ? 'transparent'
                                  : 'var(--border-card)',
                              }}
                            >
                              {w}
                            </button>
                          );
                        })}
                      </div>
                    </div>

                    <div>
                      <label
                        className="block text-[11px] font-bold mb-1.5"
                        style={{ color: 'var(--text-secondary)' }}
                      >
                        Conector del Cable Incluido
                      </label>
                      <div className="grid grid-cols-1 sm:grid-cols-3 gap-1.5">
                        {CABLE_CONNECTORS.map((conn) => {
                          const active = newProdForm.cableConnector === conn;
                          return (
                            <button
                              key={conn}
                              type="button"
                              onClick={() =>
                                setNewProdForm((prev) => ({
                                  ...prev,
                                  cableConnector: conn,
                                }))
                              }
                              className="tactile-chip py-2 px-2.5 rounded-xl text-xs font-semibold cursor-pointer hig-border text-center"
                              style={{
                                backgroundColor: active
                                  ? COLORS.electricBlue
                                  : 'var(--bg-elevated-solid)',
                                color: active ? '#FFFFFF' : 'var(--text-primary)',
                                borderColor: active
                                  ? 'transparent'
                                  : 'var(--border-card)',
                              }}
                            >
                              {conn}
                            </button>
                          );
                        })}
                      </div>
                    </div>

                    <div>
                      <label
                        className="block text-[11px] font-bold mb-1.5"
                        style={{ color: 'var(--text-secondary)' }}
                      >
                        Acabado del Cable
                      </label>
                      <div className="grid grid-cols-2 gap-1.5">
                        {CABLE_FINISHES.map((fin) => {
                          const active = newProdForm.cableFinish === fin;
                          return (
                            <button
                              key={fin}
                              type="button"
                              onClick={() =>
                                setNewProdForm((prev) => ({
                                  ...prev,
                                  cableFinish: fin,
                                }))
                              }
                              className="tactile-chip py-2 px-3 rounded-xl text-xs font-bold cursor-pointer hig-border text-center"
                              style={{
                                backgroundColor: active
                                  ? COLORS.electricBlue
                                  : 'var(--bg-elevated-solid)',
                                color: active ? '#FFFFFF' : 'var(--text-primary)',
                                borderColor: active
                                  ? 'transparent'
                                  : 'var(--border-card)',
                              }}
                            >
                              {fin}
                            </button>
                          );
                        })}
                      </div>
                    </div>
                  </div>
                )}

                {/* ANKER / BELKIN */}
                {newProdForm.chargerSubtype === 'anker' && (
                  <div className="space-y-3 animate-ios-expand">
                    <div>
                      <label
                        className="block text-[11px] font-bold mb-1.5"
                        style={{ color: 'var(--text-secondary)' }}
                      >
                        Marca
                      </label>
                      <div className="grid grid-cols-2 gap-1.5">
                        {PREMIUM_BRANDS.map((brand) => {
                          const active = newProdForm.premiumBrand === brand;
                          return (
                            <button
                              key={brand}
                              type="button"
                              onClick={() =>
                                setNewProdForm((prev) => ({
                                  ...prev,
                                  premiumBrand: brand,
                                }))
                              }
                              className="tactile-chip py-2 px-3 rounded-xl text-xs font-bold cursor-pointer hig-border text-center"
                              style={{
                                backgroundColor: active
                                  ? COLORS.electricBlue
                                  : 'var(--bg-elevated-solid)',
                                color: active ? '#FFFFFF' : 'var(--text-primary)',
                                borderColor: active
                                  ? 'transparent'
                                  : 'var(--border-card)',
                              }}
                            >
                              {brand}
                            </button>
                          );
                        })}
                      </div>
                    </div>

                    <div>
                      <label
                        className="block text-[11px] font-bold mb-1.5"
                        style={{ color: 'var(--text-secondary)' }}
                      >
                        Potencia (Watts)
                      </label>
                      <div className="grid grid-cols-3 sm:grid-cols-6 gap-1.5">
                        {CHARGER_WATTS_LIST.map((w) => {
                          const active = newProdForm.watts === w;
                          return (
                            <button
                              key={w}
                              type="button"
                              onClick={() =>
                                setNewProdForm((prev) => ({ ...prev, watts: w }))
                              }
                              className="tactile-chip cop-mono py-1.5 px-2 rounded-xl text-xs font-extrabold cursor-pointer hig-border text-center"
                              style={{
                                backgroundColor: active
                                  ? COLORS.electricBlue
                                  : 'var(--bg-elevated-solid)',
                                color: active ? '#FFFFFF' : 'var(--text-primary)',
                                borderColor: active
                                  ? 'transparent'
                                  : 'var(--border-card)',
                              }}
                            >
                              {w}
                            </button>
                          );
                        })}
                      </div>
                    </div>

                    <div>
                      <label
                        className="block text-[11px] font-bold mb-1.5"
                        style={{ color: 'var(--text-secondary)' }}
                      >
                        Configuración (Cubo / Cable Tipo C o Lightning)
                      </label>
                      <div className="grid grid-cols-1 sm:grid-cols-2 gap-1.5">
                        {ANKER_BELKIN_MODALITIES.map((mod) => {
                          const active = newProdForm.ankerModality === mod;
                          return (
                            <button
                              key={mod}
                              type="button"
                              onClick={() =>
                                setNewProdForm((prev) => ({
                                  ...prev,
                                  ankerModality: mod,
                                }))
                              }
                              className="tactile-chip py-2 px-2.5 rounded-xl text-xs font-semibold cursor-pointer hig-border text-center"
                              style={{
                                backgroundColor: active
                                  ? COLORS.electricBlue
                                  : 'var(--bg-elevated-solid)',
                                color: active ? '#FFFFFF' : 'var(--text-primary)',
                                borderColor: active
                                  ? 'transparent'
                                  : 'var(--border-card)',
                              }}
                            >
                              {mod}
                            </button>
                          );
                        })}
                      </div>
                    </div>

                    {newProdForm.ankerModality !== 'Solo Cubo USB-C' && (
                      <div>
                        <label
                          className="block text-[11px] font-bold mb-1.5"
                          style={{ color: 'var(--text-secondary)' }}
                        >
                          Acabado del Cable
                        </label>
                        <div className="grid grid-cols-2 gap-1.5">
                          {CABLE_FINISHES.map((fin) => {
                            const active = newProdForm.cableFinish === fin;
                            return (
                              <button
                                key={fin}
                                type="button"
                                onClick={() =>
                                  setNewProdForm((prev) => ({
                                    ...prev,
                                    cableFinish: fin,
                                  }))
                                }
                                className="tactile-chip py-2 px-3 rounded-xl text-xs font-bold cursor-pointer hig-border text-center"
                                style={{
                                  backgroundColor: active
                                    ? COLORS.electricBlue
                                    : 'var(--bg-elevated-solid)',
                                  color: active ? '#FFFFFF' : 'var(--text-primary)',
                                  borderColor: active
                                    ? 'transparent'
                                    : 'var(--border-card)',
                                }}
                              >
                                {fin}
                              </button>
                            );
                          })}
                        </div>
                      </div>
                    )}
                  </div>
                )}
              </div>
            )}

            {/* 2. Categoría: Forros / Fundas */}
            {newProdForm.type === 'forros' && (
              <div
                className="p-3.5 rounded-2xl space-y-3 hig-border animate-ios-expand"
                style={{ backgroundColor: 'var(--bg-secondary)' }}
              >
                <div>
                  <label
                    className="block text-[11px] font-bold mb-1.5"
                    style={{ color: 'var(--text-secondary)' }}
                  >
                    Material del Forro / Funda
                  </label>
                  <div className="grid grid-cols-2 gap-1.5">
                    {CASE_MATERIALS.map((mat) => {
                      const active = newProdForm.material === mat;
                      return (
                        <button
                          key={mat}
                          type="button"
                          onClick={() =>
                            setNewProdForm((prev) => ({ ...prev, material: mat }))
                          }
                          className="tactile-chip py-2 px-2.5 rounded-xl text-xs font-semibold cursor-pointer hig-border text-center"
                          style={{
                            backgroundColor: active
                              ? COLORS.electricBlue
                              : 'var(--bg-elevated-solid)',
                            color: active ? '#FFFFFF' : 'var(--text-primary)',
                            borderColor: active ? 'transparent' : 'var(--border-card)',
                          }}
                        >
                          {mat}
                        </button>
                      );
                    })}
                  </div>
                </div>

                <div>
                  <div className="flex items-center justify-between mb-1.5">
                    <label
                      className="text-[11px] font-bold"
                      style={{ color: 'var(--text-secondary)' }}
                    >
                      Moldes de iPhone Compatibles
                    </label>
                    <span
                      className="text-[10px] font-semibold"
                      style={{ color: COLORS.electricBlue }}
                    >
                      {newProdForm.selectedModels.length} seleccionados
                    </span>
                  </div>
                  <div className="flex flex-wrap gap-1.5">
                    {IPHONE_SHARED_MODELS.map((model) => {
                      const selected = newProdForm.selectedModels.includes(model);
                      return (
                        <button
                          key={model}
                          type="button"
                          onClick={() => handleToggleModelSelection(model)}
                          className="tactile-chip px-2.5 py-1.5 rounded-xl text-xs font-semibold cursor-pointer hig-border"
                          style={{
                            backgroundColor: selected
                              ? COLORS.electricBlueSoft
                              : 'var(--bg-elevated-solid)',
                            color: selected
                              ? COLORS.electricBlue
                              : 'var(--text-secondary)',
                            borderColor: selected
                              ? COLORS.electricBlue
                              : 'var(--border-card)',
                          }}
                        >
                          {selected ? `✓ ${model}` : model}
                        </button>
                      );
                    })}
                  </div>
                </div>
              </div>
            )}

            {/* 3. Categoría: Audio / AirPods */}
            {newProdForm.type === 'audio' && (
              <div
                className="p-3.5 rounded-2xl space-y-3 hig-border animate-ios-expand"
                style={{ backgroundColor: 'var(--bg-secondary)' }}
              >
                <div>
                  <label
                    className="block text-[11px] font-bold mb-1.5"
                    style={{ color: 'var(--text-secondary)' }}
                  >
                    Modelo de AirPods / Audio
                  </label>
                  <div className="grid grid-cols-2 gap-1.5">
                    {AUDIO_MODELS.map((model) => {
                      const active = newProdForm.audioModel === model;
                      return (
                        <button
                          key={model}
                          type="button"
                          onClick={() =>
                            setNewProdForm((prev) => ({
                              ...prev,
                              audioModel: model,
                            }))
                          }
                          className="tactile-chip py-2.5 px-2.5 rounded-xl text-xs font-bold cursor-pointer hig-border text-center"
                          style={{
                            backgroundColor: active
                              ? COLORS.electricBlue
                              : 'var(--bg-elevated-solid)',
                            color: active ? '#FFFFFF' : 'var(--text-primary)',
                            borderColor: active ? 'transparent' : 'var(--border-card)',
                          }}
                        >
                          {model}
                        </button>
                      );
                    })}
                  </div>
                </div>

                <div>
                  <label
                    className="block text-[11px] font-bold mb-1.5"
                    style={{ color: 'var(--text-secondary)' }}
                  >
                    Tipo de Conexión / Estuche
                  </label>
                  <div className="grid grid-cols-3 gap-1.5">
                    {AUDIO_CONNECTIONS.map((conn) => {
                      const active = newProdForm.audioConnection === conn;
                      return (
                        <button
                          key={conn}
                          type="button"
                          onClick={() =>
                            setNewProdForm((prev) => ({
                              ...prev,
                              audioConnection: conn,
                            }))
                          }
                          className="tactile-chip py-2 px-2.5 rounded-xl text-xs font-semibold cursor-pointer hig-border text-center"
                          style={{
                            backgroundColor: active
                              ? COLORS.electricBlue
                              : 'var(--bg-elevated-solid)',
                            color: active ? '#FFFFFF' : 'var(--text-primary)',
                            borderColor: active ? 'transparent' : 'var(--border-card)',
                          }}
                        >
                          {conn}
                        </button>
                      );
                    })}
                  </div>
                </div>
              </div>
            )}
          </>
        )}

        {/* Tarjeta de FICHA TÉCNICA (Rotulada únicamente como FICHA TÉCNICA) */}
        <div
          className="p-3 rounded-2xl flex flex-col gap-1.5 hig-border animate-ios-expand"
          style={{
            backgroundColor: 'var(--bg-primary)',
            borderColor: COLORS.electricBlue,
          }}
        >
          <div className="flex items-center justify-between gap-2">
            <span
              className="text-[10px] font-bold uppercase tracking-wider"
              style={{ color: COLORS.electricBlue }}
            >
              FICHA TÉCNICA
            </span>
            <span
              className="text-[10px] font-bold px-2 py-0.5 rounded-full"
              style={{
                backgroundColor: 'var(--bg-secondary)',
                color: 'var(--text-secondary)',
              }}
            >
              {autoGeneratedProductMeta.category}
            </span>
          </div>
          <div className="text-sm font-bold">{autoGeneratedProductMeta.name}</div>
          <div className="flex flex-wrap gap-1.5">
            {autoGeneratedProductMeta.specs.map((sp) => (
              <span
                key={sp}
                className="text-[11px] font-semibold px-2.5 py-0.5 rounded-lg"
                style={{
                  backgroundColor: COLORS.electricBlueSoft,
                  color: COLORS.electricBlue,
                }}
              >
                {sp}
              </span>
            ))}
          </div>
        </div>

        {/* C. Precios en COP (Formateo automático $50,000), Stock Inicial y Garantía */}
        <div className="grid grid-cols-2 sm:grid-cols-4 gap-2">
          <div>
            <label
              className="block text-[10px] font-semibold mb-1"
              style={{ color: 'var(--text-secondary)' }}
            >
              Precio Venta *
            </label>
            <input
              type="text"
              inputMode="numeric"
              required
              placeholder="$50,000"
              value={formatPriceInput(newProdForm.salePrice)}
              onChange={(e) =>
                setNewProdForm({
                  ...newProdForm,
                  salePrice: parsePriceInput(e.target.value),
                })
              }
              className="hig-input cop-mono w-full text-xs font-bold"
            />
          </div>
          <div>
            <label
              className="block text-[10px] font-semibold mb-1"
              style={{ color: 'var(--text-secondary)' }}
            >
              Costo Compra *
            </label>
            <input
              type="text"
              inputMode="numeric"
              required
              placeholder="$20,000"
              value={formatPriceInput(newProdForm.unitCost)}
              onChange={(e) =>
                setNewProdForm({
                  ...newProdForm,
                  unitCost: parsePriceInput(e.target.value),
                })
              }
              className="hig-input cop-mono w-full text-xs font-bold"
            />
          </div>
          <div>
            <label
              className="block text-[10px] font-semibold mb-1"
              style={{ color: 'var(--text-secondary)' }}
            >
              Stock Inicial
            </label>
            <input
              type="number"
              min="0"
              required
              value={newProdForm.stock}
              onChange={(e) =>
                setNewProdForm({ ...newProdForm, stock: e.target.value })
              }
              className="hig-input cop-mono w-full text-xs font-bold"
            />
          </div>
          <div>
            <label
              className="block text-[10px] font-semibold mb-1"
              style={{ color: 'var(--text-secondary)' }}
            >
              Garantía (Días)
            </label>
            <input
              type="number"
              min="0"
              required
              value={newProdForm.defaultWarrantyDays}
              onChange={(e) =>
                setNewProdForm({
                  ...newProdForm,
                  defaultWarrantyDays: e.target.value,
                })
              }
              className="hig-input cop-mono w-full text-xs font-bold"
            />
          </div>
        </div>

        <IOSSupplierPicker
          suppliers={suppliers}
          selectedSupplierId={newProdForm.supplierId}
          lastSupplierId={lastSupplierId}
          onSelect={(supId) =>
            setNewProdForm({ ...newProdForm, supplierId: supId })
          }
          label="Tienda / Proveedor de Origen"
        />

        <div className="pt-1 pb-2">
          <button
            type="submit"
            className="btn-electric w-full py-3 text-xs font-bold cursor-pointer"
          >
            Guardar en Inventario
          </button>
        </div>
      </form>
    </IOSBottomSheet>
  );
}

