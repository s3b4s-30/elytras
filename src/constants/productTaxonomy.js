/**
 * Genera de forma pura la Ficha Técnica (name, category, specs) a partir del estado del formulario.
 */
export function buildAutoGeneratedProductMeta(newProdForm) {
  if (newProdForm.basedOnProductId && newProdForm.customName.trim()) {
    const parsedSpecs = newProdForm.customSpecsText
      .split(',')
      .map((s) => s.trim())
      .filter(Boolean);
    return {
      name: newProdForm.customName.trim(),
      category: newProdForm.customCategory.trim() || 'Cargadores y Cables',
      specs: parsedSpecs.length > 0 ? parsedSpecs : ['Compatible iPhone'],
    };
  }

  if (newProdForm.type === 'cargadores') {
    if (newProdForm.chargerSubtype === 'cubito') {
      return {
        name: `Cubito Cargador ${newProdForm.cuboBrand} ${newProdForm.watts}`,
        category: 'Cargadores y Cables',
        specs: [
          'Cubito Cargador',
          newProdForm.cuboBrand,
          newProdForm.watts,
          'Carga Rápida USB-C',
        ],
      };
    }

    if (newProdForm.chargerSubtype === 'cable') {
      return {
        name: `Cable ${newProdForm.cuboBrand} ${newProdForm.cableConnector} ${newProdForm.cableFinish} (${newProdForm.watts})`,
        category: 'Cargadores y Cables',
        specs: [
          newProdForm.cableConnector,
          `Cable ${newProdForm.cableFinish}`,
          newProdForm.cuboBrand,
          newProdForm.watts,
        ],
      };
    }

    if (newProdForm.chargerSubtype === 'completo') {
      return {
        name: `Cargador Completo ${newProdForm.cuboBrand} ${newProdForm.watts} + Cable ${newProdForm.cableConnector} ${newProdForm.cableFinish}`,
        category: 'Cargadores y Cables',
        specs: [
          'Completo [Cubo + Cable]',
          newProdForm.cuboBrand,
          newProdForm.watts,
          newProdForm.cableConnector,
          `Cable ${newProdForm.cableFinish}`,
        ],
      };
    }

    // Subtipo: Anker / Belkin
    const isSoloCubo = newProdForm.ankerModality === 'Solo Cubo USB-C';
    return {
      name: isSoloCubo
        ? `Cubito Cargador ${newProdForm.premiumBrand} ${newProdForm.watts}`
        : `${newProdForm.premiumBrand} ${newProdForm.watts} ${newProdForm.ankerModality} (${newProdForm.cableFinish})`,
      category: 'Cargadores y Cables',
      specs: isSoloCubo
        ? [newProdForm.premiumBrand, newProdForm.watts, 'Solo Cubo USB-C']
        : [
            newProdForm.premiumBrand,
            newProdForm.watts,
            newProdForm.ankerModality,
            `Cable ${newProdForm.cableFinish}`,
          ],
    };
  }

  if (newProdForm.type === 'forros') {
    const models =
      newProdForm.selectedModels.length > 0
        ? newProdForm.selectedModels
        : ['iPhone 13 / 14'];
    return {
      name: `Forro ${newProdForm.material} (${models.join(', ')})`,
      category: 'Forros y Fundas',
      specs: [...models, newProdForm.material],
    };
  }

  // Audio / AirPods
  return {
    name: `${newProdForm.audioModel} (${newProdForm.audioConnection})`,
    category: 'Audio',
    specs: [
      newProdForm.audioModel,
      `Conexión / Estuche ${newProdForm.audioConnection}`,
    ],
  };
}

